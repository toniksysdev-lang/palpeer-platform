const {
  AndroidConfig,
  withAndroidManifest,
  withAppDelegate,
  withDangerousMod,
  withInfoPlist,
  withPodfile,
} = require('expo/config-plugins');
const fs = require('node:fs');
const path = require('node:path');

/**
 * Certificate (SPKI) pinning for Android (network_security_config) and iOS (TrustKit).
 *
 * Set EXPO_PUBLIC_API_SSL_PINS to comma-separated base64 SHA-256 SPKI hashes for the API host
 * (leaf and/or intermediate). Empty → no pin-set (dev / Expo Go friendly).
 *
 * Pins for production/preview are written by `node scripts/apply-ops-security.mjs` into eas.json.
 */
function parsePins(raw) {
  return String(raw || '')
    .split(',')
    .map((p) => p.trim())
    .filter(Boolean);
}

function hostFromApiUrl(apiUrl) {
  try {
    return new URL(String(apiUrl || '').trim()).hostname;
  } catch {
    return '';
  }
}

function buildNetworkSecurityConfig({ host, pins, cleartext }) {
  const pinDigest = pins
    .map((pin) => `            <pin digest="SHA-256">${pin}</pin>`)
    .join('\n');
  const pinSet =
    host && pins.length
      ? `
    <domain-config cleartextTrafficPermitted="false">
        <domain includeSubdomains="true">${host}</domain>
        <pin-set expiration="2028-12-31">
${pinDigest}
        </pin-set>
    </domain-config>`
      : '';

  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withSslPinning.js — do not edit by hand -->
<network-security-config>
    <base-config cleartextTrafficPermitted="${cleartext ? 'true' : 'false'}">
        <trust-anchors>
            <certificates src="system" />
        </trust-anchors>
    </base-config>${pinSet}
</network-security-config>
`;
}

function withAndroidSslPinning(config, { host, pins, cleartext }) {
  config = withDangerousMod(config, [
    'android',
    async (mod) => {
      const xmlDir = path.join(mod.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
      fs.mkdirSync(xmlDir, { recursive: true });
      const target = path.join(xmlDir, 'network_security_config.xml');
      fs.writeFileSync(target, buildNetworkSecurityConfig({ host, pins, cleartext }), 'utf8');
      return mod;
    },
  ]);

  return withAndroidManifest(config, (mod) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(mod.modResults);
    application.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    return mod;
  });
}

function withIosSslPinning(config, { host, pins }) {
  if (!host || pins.length === 0) {
    return config;
  }

  config = withInfoPlist(config, (mod) => {
    mod.modResults.TSKConfiguration = {
      TSKSwizzleNetworkDelegates: true,
      TSKPinnedDomains: {
        [host]: {
          TSKEnforcePinning: true,
          TSKIncludeSubdomains: true,
          TSKPublicKeyHashes: pins,
        },
      },
    };
    return mod;
  });

  config = withPodfile(config, (mod) => {
    const contents = mod.modResults.contents;
    if (!contents.includes("pod 'TrustKit'")) {
      mod.modResults.contents = contents.replace(
        /use_expo_modules!/,
        `use_expo_modules!\n  pod 'TrustKit'`,
      );
    }
    return mod;
  });

  config = withAppDelegate(config, (mod) => {
    let contents = mod.modResults.contents;
    const isSwift = mod.modResults.language === 'swift' || contents.includes('import Expo');

    if (isSwift) {
      if (!contents.includes('import TrustKit')) {
        contents = contents.replace(/import Expo\n/, 'import Expo\nimport TrustKit\n');
      }
      if (!contents.includes('TrustKit.initSharedInstance')) {
        const hook =
          '    if let trustKitConfig = Bundle.main.object(forInfoDictionaryKey: "TSKConfiguration") as? [String: Any] {\n' +
          '      TrustKit.initSharedInstance(withConfiguration: trustKitConfig)\n' +
          '    }\n';
        if (contents.includes('factory.startReactNative(')) {
          contents = contents.replace(
            'factory.startReactNative(',
            `${hook}    factory.startReactNative(`,
          );
        } else if (contents.includes('return super.application(')) {
          contents = contents.replace(
            'return super.application(',
            `${hook}    return super.application(`,
          );
        } else {
          contents += `\n// TrustKit init could not be auto-inserted; add TrustKit.initSharedInstance manually.\n`;
        }
      }
    } else {
      if (!contents.includes('#import <TrustKit/TrustKit.h>')) {
        contents = contents.replace(
          /#import "AppDelegate.h"/,
          `#import "AppDelegate.h"\n#import <TrustKit/TrustKit.h>`,
        );
      }
      if (!contents.includes('initSharedInstanceWithConfiguration')) {
        const hook =
          '  NSDictionary *trustKitConfig = [[NSBundle mainBundle] objectForInfoDictionaryKey:@"TSKConfiguration"];\n' +
          '  if (trustKitConfig != nil) {\n' +
          '    [TrustKit initSharedInstanceWithConfiguration:trustKitConfig];\n' +
          '  }\n';
        contents = contents.replace(
          'self.initialProps = @{};',
          `self.initialProps = @{};\n${hook}`,
        );
      }
    }

    mod.modResults.contents = contents;
    return mod;
  });

  return config;
}

const withSslPinning = (config) => {
  const pins = parsePins(process.env.EXPO_PUBLIC_API_SSL_PINS);
  const host = hostFromApiUrl(process.env.EXPO_PUBLIC_API_BASE_URL);
  const env = process.env.EXPO_PUBLIC_ENV ?? 'development';
  const cleartext = env === 'development';

  config = withAndroidSslPinning(config, { host, pins, cleartext });
  config = withIosSslPinning(config, { host, pins });
  return config;
};

module.exports = withSslPinning;
